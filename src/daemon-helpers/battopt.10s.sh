#!/bin/bash

# SwiftBar plugin for BattOpt.
# Install or symlink this file as:
#   ~/SwiftBar/battopt.10s.sh

set -u

DASH="${HOME}/.battopt-swiftbar"
DISPATCH="$DASH/dispatch.sh"
BAT="${BAT:-/usr/local/bin/battopt}"
CONFIG="$DASH/config"
CACHE="$DASH/.status_cache"
ACTIVE_MODE_FILE="$DASH/.active_mode"
POWER_MODE="$DASH/power_mode.sh"
ICON="$DASH/icons/battopt.png"

mkdir -p "$DASH"

if [ -f "$DASH/.user_shutdown" ]; then
    printf 'BattOpt: Off | color=gray\n'
    printf -- '---\n'
    printf 'BattOpt is shut down | color=gray\n'
    printf 'Open BattOpt.app to restore | bash=/usr/bin/open param1=/Applications/BattOpt.app terminal=false\n'
    exit 0
fi

dispatch() {
    printf '%s\n' "$DISPATCH" "$1" >/dev/null
    bash "$DISPATCH" "$@" >/dev/null 2>&1 &
}

read_config() {
    LAST_UPPER=85
    LAST_LOWER=80
    SAILING=true
    SAIL_GAP=10

    if [ -f "$CONFIG" ]; then
        # The config is generated by dispatch.sh and contains simple shell
        # assignments. Do not source arbitrary files from the plugin folder.
        while IFS='=' read -r key value; do
            case "$key" in
                LAST_UPPER|LAST_LOWER|SAILING|SAIL_GAP)
                    case "$value" in
                        ''|*[!0-9a-zA-Z_]*) ;;
                        *) printf -v "$key" '%s' "$value" ;;
                    esac
                    ;;
            esac
        done < "$CONFIG"
    fi
}

battery_status() {
    local status
    status=$(sudo -n "$BAT" status 2>/dev/null || true)

    if [ -n "$status" ]; then
        printf '%s\n' "$status"
        printf '%s\n' "$status" > "$CACHE.tmp.$$" 2>/dev/null &&
            mv "$CACHE.tmp.$$" "$CACHE" 2>/dev/null || true
    elif [ -f "$CACHE" ]; then
        cat "$CACHE"
    fi
}

extract_number() {
    printf '%s\n' "$1" | grep -oE "$2" | grep -oE '[0-9.]+' | head -1
}

read_config

STATUS=$(battery_status)
PCT=$(extract_number "$STATUS" 'Capacity [0-9]+')
HEALTH=$(extract_number "$STATUS" 'Health [0-9.]+')
SMC_UPPER=$(extract_number "$STATUS" 'upper limit [0-9]+')
SMC_LOWER=$(extract_number "$STATUS" 'lower limit [0-9]+')

[ -n "$PCT" ] || PCT='?'
[ -n "$HEALTH" ] || HEALTH='?'

ACTIVE_MODE=$(cat "$ACTIVE_MODE_FILE" 2>/dev/null | tr -d '[:space:]')
[ -n "$ACTIVE_MODE" ] || ACTIVE_MODE=idle

POWER_PROFILE=$(bash "$POWER_MODE" status 2>/dev/null | tr -d '[:space:]')
[ -n "$POWER_PROFILE" ] || POWER_PROFILE=balanced

AC_STATE=$(pmset -g batt 2>/dev/null | grep -q 'AC Power' && echo 'AC' || echo 'Battery')

case "$ACTIVE_MODE" in
    discharge)
        TITLE="BattOpt: ${PCT}% ↓"
        COLOR="#d08770"
        ;;
    charge_full)
        TITLE="BattOpt: ${PCT}% ↑"
        COLOR="#a3be8c"
        ;;
    calibration)
        TITLE="BattOpt: ${PCT}% ⚙"
        COLOR="#ebcb8b"
        ;;
    hold)
        TITLE="BattOpt: ${PCT}% ⏸"
        COLOR="#88c0d0"
        ;;
    *)
        TITLE="BattOpt: ${PCT}%"
        COLOR="white"
        ;;
esac

printf '%s | color=%s' "$TITLE" "$COLOR"
[ -f "$ICON" ] && printf ' | image=%s' "$ICON"
printf '\n'

printf -- '---\n'
printf 'Battery: %s%% (%s) | color=%s\n' "$PCT" "$AC_STATE" "$COLOR"
printf 'Health: %s%%\n' "$HEALTH"
printf 'Active Mode: %s\n' "$ACTIVE_MODE"
printf 'Power Mode: %s\n' "$POWER_PROFILE"
printf -- '---\n'

printf 'Charge Limits | color=gray\n'
printf 'Set Custom Limit... | bash=%s param1=limit_custom terminal=false refresh=true\n' "$DISPATCH"
printf 'Hold Current Level | bash=%s param1=stop_now terminal=false refresh=true\n' "$DISPATCH"
printf 'Disable Charge Limit | bash=%s param1=disable_limit terminal=false refresh=true\n' "$DISPATCH"
printf 'Charge to 100%% | bash=%s param1=charge_full terminal=false refresh=true\n' "$DISPATCH"

if [ "$SAILING" = "true" ]; then
    printf 'Sailing Mode: ON (%s%% gap) | bash=%s param1=sail_off terminal=false refresh=true\n' "$SAIL_GAP" "$DISPATCH"
else
    printf 'Sailing Mode: OFF | bash=%s param1=sail_on terminal=false refresh=true\n' "$DISPATCH"
fi

printf 'Set Sailing Gap... | bash=%s param1=sail_gap_set param2=custom terminal=false refresh=true\n' "$DISPATCH"
printf -- '---\n'

printf 'Discharge and Calibration | color=gray\n'
printf 'Smart Discharge... | bash=%s param1=smart_discharge terminal=false refresh=true\n' "$DISPATCH"
printf 'Stop Discharge | bash=%s param1=kill_discharge terminal=false refresh=true\n' "$DISPATCH"
printf 'Start Calibration | bash=%s param1=calibrate terminal=false refresh=true\n' "$DISPATCH"
printf 'Stop Calibration | bash=%s param1=cal_stop terminal=false refresh=true\n' "$DISPATCH"
printf -- '---\n'

printf 'Power Mode: %s | color=gray\n' "$POWER_PROFILE"
printf 'Fast Sleep | bash=%s param1=power_mode_fast terminal=false refresh=true\n' "$DISPATCH"
printf 'Balanced | bash=%s param1=power_mode_balanced terminal=false refresh=true\n' "$DISPATCH"
printf 'Always Awake | bash=%s param1=power_mode_awake terminal=false refresh=true\n' "$DISPATCH"
printf 'Deep Sleep | bash=%s param1=power_mode_deep terminal=false refresh=true\n' "$DISPATCH"
printf 'Custom Power Mode... | bash=%s param1=power_mode_custom terminal=false refresh=true\n' "$DISPATCH"

printf -- '---\n'
printf 'Sleep Tools | color=gray\n'
printf 'Arm for Sleep | bash=%s param1=arm_sleep terminal=false refresh=true\n' "$DISPATCH"
printf 'Pre-Sleep Cleanup | bash=%s param1=pre_sleep_now terminal=false refresh=true\n' "$DISPATCH"
printf 'Restore After Wake | bash=%s param1=post_wake_now terminal=false refresh=true\n' "$DISPATCH"
printf 'Sleep Report | bash=%s param1=sleep_report terminal=false refresh=true\n' "$DISPATCH"

printf -- '---\n'
printf 'Diagnostics | color=gray\n'
printf 'Refresh | refresh=true\n'
printf 'BattOpt Details | bash=%s param1=details terminal=false refresh=true\n' "$DISPATCH"
printf 'Open Actions Log | bash=%s param1=logs_actions terminal=false\n' "$DISPATCH"
printf 'Save Diagnostic Bundle | bash=%s param1=logs_ai_bundle terminal=false refresh=true\n' "$DISPATCH"
printf 'Reset to Defaults | bash=%s param1=reset_defaults terminal=false refresh=true\n' "$DISPATCH"
printf 'Shut Down BattOpt | bash=%s param1=shutdown terminal=false refresh=true\n' "$DISPATCH"
